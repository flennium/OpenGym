import PDFDocument from "pdfkit";
import { createWriteStream, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const output = resolve("output/pdf/opengym-branded-receipt-sample.pdf");
mkdirSync(resolve("output/pdf"), { recursive: true });
const doc = new PDFDocument({ size: "A4", margin: 54, info: { Title: "OpenGym branded receipt sample" } });
doc.pipe(createWriteStream(output));
const left = 54, right = doc.page.width - 54, width = right - left, accent = "#147D5D";
doc.roundedRect(left, 48, 62, 62, 8).fill(accent);
doc.fillColor("#FFFFFF").font("Helvetica-Bold").fontSize(25).text("NG", left, 67, { width: 62, align: "center" });
doc.fillColor(accent).font("Helvetica-Bold").fontSize(22).text("Northside Gym", left + 82, 52);
doc.fillColor("#5E6870").font("Helvetica").fontSize(8.5).text("18 Fitness Avenue, Algiers  |  +213 555 123 456  |  hello@northside.dz  |  Tax ID: DZ-123456", left + 82, 82, { width: width - 82, lineGap: 2 });
doc.moveTo(left, 126).lineTo(right, 126).lineWidth(2).strokeColor(accent).stroke();
doc.fillColor("#17202A").font("Helvetica-Bold").fontSize(16).text("Payment receipt", left, 154);
doc.fillColor("#64717A").font("Helvetica").fontSize(9).text("Receipt 2026-000001", right - 180, 158, { width: 180, align: "right" });
const row = (label, value, top) => { doc.fillColor("#64717A").font("Helvetica").fontSize(9).text(label, left, top); doc.fillColor("#17202A").font("Helvetica-Bold").fontSize(10.5).text(value, left + 145, top, { width: width - 145, align: "right" }); doc.moveTo(left, top + 22).lineTo(right, top + 22).lineWidth(.5).strokeColor("#DDE2E4").stroke(); };
row("Paid for", "Monthly membership", 204);
row("Membership period", "2026-09-01 to 2026-09-30", 244);
row("Member", "Nadia Bensaid", 284);
row("Payment date", "12 September 2026 at 08:30", 324);
row("Payment method", "Card", 364);
row("Payment status", "Paid", 404);
doc.roundedRect(left, 466, width, 92, 8).fill(accent);
doc.fillColor("#FFFFFF").font("Helvetica").fontSize(10).text("Amount paid", left + 20, 488);
doc.font("Helvetica-Bold").fontSize(24).text("DZD 5,000.00", left + 20, 507, { width: width - 40, align: "right" });
doc.fillColor("#64717A").font("Helvetica").fontSize(9).text("Thank you for training with Northside Gym.", left, doc.page.height - 100, { width, align: "center" });
doc.fontSize(7.5).text("Generated by OpenGym - Keep this receipt for your records.", left, doc.page.height - 64, { width, align: "center" });
doc.end();
